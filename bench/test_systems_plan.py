"""Validate the generated, evidence-aware 50-system plan.

The execution source is docs/systems-plan.json. docs/SYSTEMS.md is a rendered
operator dashboard, while docs/SYSTEMS-DETAILS.md retains historical rationale.
The planner owns validation so its command and this hermetic gate agree.

    uv run python bench/test_systems_plan.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "docs" / "systems-plan.json"
DASHBOARD = ROOT / "docs" / "SYSTEMS.md"
DETAILS = ROOT / "docs" / "SYSTEMS-DETAILS.md"
PLANNER = ROOT / "scripts" / "systems_plan.py"

passed = failed = 0


def check(ok: bool, name: str, detail: str = "") -> None:
    global passed, failed
    if ok:
        passed += 1
        print(f"  [PASS] {name}")
    else:
        failed += 1
        print(f"  [FAIL] {name}  {detail}")


def main() -> int:
    print("[1] the registry is the authoritative execution source")
    check(REGISTRY.exists(), "docs/systems-plan.json exists")
    check(DASHBOARD.exists(), "docs/SYSTEMS.md dashboard exists")
    check(DETAILS.exists(), "docs/SYSTEMS-DETAILS.md archive exists")
    check(PLANNER.exists(), "systems_plan.py renderer exists")
    if not REGISTRY.exists():
        return 1

    print("\n[2] planner validation covers generated-state drift")
    result = subprocess.run(
        [sys.executable, str(PLANNER), "check"], cwd=ROOT, capture_output=True, text=True
    )
    check(result.returncode == 0, "planner check passes", result.stdout + result.stderr)

    data = json.loads(REGISTRY.read_text(encoding="utf-8"))
    systems = data.get("systems", [])
    expected = [f"S{number:02d}" for number in range(1, 51)]

    print("\n[3] all execution state is structured and evidence-aware")
    check([system.get("id") for system in systems] == expected, "S01..S50 present and ordered")
    tasks = [task for system in systems for task in system.get("tasks", [])]
    check(bool(tasks), "registry contains tasks")
    check(all(system.get("status_evidence") for system in systems),
          "every system status names evidence")
    check(all(task.get("gate") for task in tasks), "every task names a gate")
    # "unregistered-test" is a real bench/ script the hermetic runner does not carry
    # (check_public_clean.py, behavioral_suite.py). Weaker than a registered test — nothing runs it
    # on push — but it is neither manual nor planned, and folding it into either hid a real gate.
    check(all(task.get("verification") in {"hermetic-test", "exempt-test", "unregistered-test",
                                           "planned-test", "manual"}
              for task in tasks), "every task declares a supported verification kind")
    check(all(task.get("scope") == "task" for task in tasks),
          "every item is a bounded task, not an untyped initiative")
    check(all(task.get("evidence") for task in tasks if task.get("state") == "done"),
          "every completed task carries evidence")
    planned = [task for task in tasks if task.get("verification") == "planned-test"]
    check(all("new `test_" in task.get("gate", "") for task in planned),
          "each planned test is declared on the task that needs it")

    print("\n[4] the dashboard is generated, compact, and traceable")
    dashboard = DASHBOARD.read_text(encoding="utf-8") if DASHBOARD.exists() else ""
    check(dashboard.startswith("<!-- Generated by scripts/systems_plan.py"),
          "dashboard declares its renderer")
    check("docs/systems-plan.json" in dashboard and "docs/SYSTEMS-DETAILS.md" in dashboard,
          "dashboard names its source and archive")
    check("## Systems" in dashboard and "**Totals:" in dashboard,
          "dashboard carries the operational table and derived totals")

    print("\n[5] the other planning documents point to the same source")
    todo = (ROOT / "TODO.md").read_text(encoding="utf-8")
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    check("docs/systems-plan.json" in todo[:5000], "TODO.md names the execution registry up front")
    check("docs/systems-plan.json" in readme[:8000], "README.md names the execution registry up front")

    print(f"\n=== {passed}/{passed + failed} checks passed ===")
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main())